//! Which provider a run talks to, and the facts about it that `review` decides
//! by provider rather than by run.
//!
//! The provider used to be a string end to end, matched in a dozen places with
//! `_ =>` fallbacks, so a new name added to the known list compiled and quietly
//! fell into every default arm: the wrong sandbox text, the wrong cutoff, no
//! graceful stop. It is parsed once where it enters - the config files, the
//! command line, a session's record - and everything past that point matches
//! on the enum exhaustively, with no wildcard, so adding a variant makes the
//! compiler list every site that has to decide something about it.
//!
//! Persisted rows (the sidecar, the in-flight markers, the audit log) keep the
//! provider as the string they were written with: a row naming a provider that
//! `review` no longer drives must still be readable by `review sessions`. It is
//! parsed at the point a row is acted on, and a name that does not parse is
//! refused there.
//!
//! What lives here is only what is a fact about the provider whatever the
//! launch. How a launch's permissions are prepared, translated, recorded and
//! restored depends on the launch (fresh or resumed, which level), so those
//! stay exhaustive matches in the runner-facing code (`provider::invoke`,
//! `provider::Permissions`) rather than flags
//! here, from which orchestration would have to reconstruct the behaviour.

use std::time::Duration;

/// A provider `review` can run. The canonical spelling (`as_str`) is the one
/// written in config tables, on the command line and in every recorded row.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, clap::ValueEnum)]
pub enum Provider {
    Claude,
    Codex,
    Grok,
    Maki,
}

impl Provider {
    /// Every provider, in declaration order. Generated by `ValueEnum` from the
    /// variants themselves, so it cannot miss one; no variant may be skipped.
    pub fn all() -> &'static [Provider] {
        <Provider as clap::ValueEnum>::value_variants()
    }

    pub fn as_str(self) -> &'static str {
        match self {
            Provider::Claude => "claude",
            Provider::Codex => "codex",
            Provider::Grok => "grok",
            Provider::Maki => "maki",
        }
    }

    /// `claude, codex, grok, maki`, for error messages and help.
    pub fn supported() -> String {
        names(Provider::all().iter().copied())
    }

    /// The executable looked for on `PATH` to decide whether it is installed.
    pub fn binary(self) -> &'static str {
        match self {
            Provider::Claude => "claude",
            Provider::Codex => "codex",
            Provider::Grok => "grok",
            Provider::Maki => "maki",
        }
    }

    /// Whether a turn in flight can be ended with `SIGINT` and leave a session
    /// that resumes. codex, claude and maki all close the turn on `SIGINT` (see
    /// `reference/codex.md`, `reference/claude.md` and `reference/maki.md`);
    /// grok has no such lever.
    ///
    /// The one answer read by `review interrupt`, `review message` and the
    /// signal supervisor's wait for unrecorded runs (`Unrecorded`), which used
    /// to hold two separate copies of it. Answering `true` here is a promise the
    /// runner must keep - offer its keeper's pid, observe the stop channel,
    /// classify the interruption - and a runner-level test is what shows it
    /// does; this only keeps the callers agreeing.
    pub fn interruptible(self) -> bool {
        match self {
            Provider::Claude | Provider::Codex | Provider::Maki => true,
            Provider::Grok => false,
        }
    }

    /// How long since a session was last touched before `review message`
    /// refuses to resume it, because the provider's prompt cache has gone cold.
    /// The lifetime is set by whoever serves the model, not by the harness.
    /// For claude and codex that host is fixed; maki's depends on the
    /// `--model` it runs, so one per-provider value is only a placeholder for
    /// maki and it takes the general cutoff.
    pub fn stale_cutoff(self) -> Duration {
        match self {
            Provider::Codex => crate::timings::STALE_SESSION_CODEX,
            Provider::Claude | Provider::Grok | Provider::Maki => crate::timings::STALE_SESSION,
        }
    }

    /// The interruptible providers, as `claude, codex or maki`, for help and
    /// refusal text.
    pub fn interruptible_names() -> String {
        or_names(
            Provider::all()
                .iter()
                .copied()
                .filter(|p| p.interruptible()),
        )
    }

    /// The providers whose turns cannot be interrupted, as `grok`.
    pub fn uninterruptible_names() -> String {
        or_names(
            Provider::all()
                .iter()
                .copied()
                .filter(|p| !p.interruptible()),
        )
    }

    /// The stale cutoffs as help prose: `27 minutes ago (codex) or 55 minutes
    /// ago (claude, grok, maki)`, providers grouped by cutoff, shortest first.
    pub fn stale_cutoff_prose() -> String {
        let mut by_cutoff: std::collections::BTreeMap<Duration, Vec<Provider>> =
            std::collections::BTreeMap::new();
        for p in Provider::all() {
            by_cutoff.entry(p.stale_cutoff()).or_default().push(*p);
        }
        by_cutoff
            .into_iter()
            .map(|(cutoff, ps)| {
                format!(
                    "{} minutes ago ({})",
                    cutoff.as_secs() / 60,
                    names(ps.into_iter())
                )
            })
            .collect::<Vec<_>>()
            .join(" or ")
    }
}

fn names(ps: impl Iterator<Item = Provider>) -> String {
    ps.map(Provider::as_str).collect::<Vec<_>>().join(", ")
}

fn or_names(ps: impl Iterator<Item = Provider>) -> String {
    let v: Vec<&str> = ps.map(Provider::as_str).collect();
    match v.split_last() {
        None => String::new(),
        Some((last, [])) => (*last).to_string(),
        Some((last, rest)) => format!("{} or {last}", rest.join(", ")),
    }
}

impl std::fmt::Display for Provider {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.as_str())
    }
}

/// A name that is not one of `review`'s providers.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UnknownProvider(pub String);

impl std::fmt::Display for UnknownProvider {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "unknown provider '{}'\n  supported: {}",
            self.0,
            Provider::supported()
        )
    }
}

impl std::error::Error for UnknownProvider {}

impl std::str::FromStr for Provider {
    type Err = UnknownProvider;

    /// Exact canonical spelling only: these names are table keys and recorded
    /// values, where a case-folded match would let two spellings of one
    /// provider coexist.
    fn from_str(s: &str) -> Result<Self, Self::Err> {
        Provider::all()
            .iter()
            .copied()
            .find(|p| p.as_str() == s)
            .ok_or_else(|| UnknownProvider(s.to_string()))
    }
}

impl serde::Serialize for Provider {
    fn serialize<S: serde::Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        s.serialize_str(self.as_str())
    }
}

/// Through `FromStr`, so a config file naming an unknown provider gets the same
/// message, with the supported list, as every other boundary.
impl<'de> serde::Deserialize<'de> for Provider {
    fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        let s = String::deserialize(d)?;
        s.parse().map_err(serde::de::Error::custom)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_provider_round_trips_through_its_name() {
        for p in Provider::all() {
            assert_eq!(p.as_str().parse::<Provider>(), Ok(*p));
            // clap's own spelling must be the canonical one, or `--provider`
            // and the config would accept different names.
            let pv = clap::ValueEnum::to_possible_value(p).expect("no variant is skipped");
            assert_eq!(pv.get_name(), p.as_str());
        }
        assert!("opencode".parse::<Provider>().is_err());
        assert!("Codex".parse::<Provider>().is_err());
    }

    #[test]
    fn help_prose_follows_the_table() {
        assert_eq!(Provider::interruptible_names(), "claude, codex or maki");
        assert_eq!(
            Provider::stale_cutoff_prose(),
            "27 minutes ago (codex) or 55 minutes ago (claude, grok, maki)"
        );
    }
}
